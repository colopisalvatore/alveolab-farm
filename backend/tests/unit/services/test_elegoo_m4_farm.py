from backend.app.services.printer_providers.elegoo.files import (
    REASON_3MF_JAMS_CC2,
    REASON_NOT_SLICED,
    REASON_UNKNOWN_TARGET,
    REASON_UNSUPPORTED_TYPE,
    REASON_WRONG_PRINTER,
    check_printable_on_cc2,
    gcode_sliced_for_cc2,
    printer_filename,
)

ORCA_CC2_TAIL = (
    "; CONFIG_BLOCK_START\n"
    "; printer_model = Elegoo Centauri Carbon 2\n"
    "; printer_settings_id = Elegoo Centauri Carbon 2 0.4 nozzle\n"
    "; CONFIG_BLOCK_END\n"
)

# --- files ---------------------------------------------------------------------


def _gcode(tmp_path, name, settings: str, body_lines: int = 10):
    path = tmp_path / name
    path.write_text("; generated by OrcaSlicer\nG28\n" + "G1 X1 Y1\n" * body_lines + settings, encoding="utf-8")
    return path


def _threemf(tmp_path, name, *, project_settings: dict | None = None, plate_gcode: str | None = None):
    path = tmp_path / name
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("3D/3dmodel.model", "<model/>")
        if project_settings is not None:
            zf.writestr("Metadata/project_settings.config", json.dumps(project_settings))
        if plate_gcode is not None:
            zf.writestr("Metadata/plate_1.gcode", plate_gcode)
    return path


class TestPrintableFiles:
    def test_orca_gcode_for_cc2_with_settings_at_the_end(self, tmp_path):
        # Orca writes its settings block after the moves; a big body pushes it
        # past the head the checker reads first.
        path = _gcode(tmp_path, "benchy.gcode", ORCA_CC2_TAIL, body_lines=60_000)
        check = check_printable_on_cc2(path)
        assert check.ok
        assert check.sliced_for == "Elegoo Centauri Carbon 2"

    def test_gcode_for_a_bambu_is_refused(self, tmp_path):
        path = _gcode(tmp_path, "p1s.gcode", "; printer_model = Bambu Lab P1S\n")
        check = check_printable_on_cc2(path)
        assert not check.ok
        assert check.reason == REASON_WRONG_PRINTER
        assert check.sliced_for == "Bambu Lab P1S"

    def test_gcode_that_names_no_printer_is_refused(self, tmp_path):
        check = check_printable_on_cc2(_gcode(tmp_path, "x.gcode", ""))
        assert check.reason == REASON_UNKNOWN_TARGET

    def test_first_generation_centauri_is_not_a_cc2(self, tmp_path):
        path = _gcode(tmp_path, "cc1.gcode", "; printer_model = Elegoo Centauri Carbon\n")
        assert check_printable_on_cc2(path).reason == REASON_WRONG_PRINTER

    def test_bambu_sliced_3mf_is_refused(self, tmp_path):
        path = _threemf(
            tmp_path,
            "plate.gcode.3mf",
            project_settings={"printer_model": "Bambu Lab P1S"},
            plate_gcode="G28\n",
        )
        check = check_printable_on_cc2(path)
        assert check.reason == REASON_WRONG_PRINTER

    def test_cc2_sliced_3mf_is_refused_but_its_target_is_read(self, tmp_path):
        """HW-M4-03: a 3MF sliced for the CC2 jams it over LAN; the library still learns who it is for."""
        a = _threemf(
            tmp_path, "a.gcode.3mf", project_settings={"printer_model": "Elegoo Centauri Carbon 2"}, plate_gcode="G28\n"
        )
        b = _threemf(tmp_path, "b.gcode.3mf", plate_gcode="G28\n" + ORCA_CC2_TAIL)
        for path in (a, b):
            check = check_printable_on_cc2(path)
            assert not check.ok
            assert check.reason == REASON_3MF_JAMS_CC2
            assert check.sliced_for == "Elegoo Centauri Carbon 2"
            assert "Export G-code" in check.message

    def test_unsliced_project_is_refused(self, tmp_path):
        path = _threemf(tmp_path, "project.3mf", project_settings={"printer_model": "Elegoo Centauri Carbon 2"})
        assert check_printable_on_cc2(path).reason == REASON_NOT_SLICED

    def test_other_types_and_broken_zips(self, tmp_path):
        stl = tmp_path / "part.stl"
        stl.write_bytes(b"solid x")
        broken = tmp_path / "broken.3mf"
        broken.write_bytes(b"not a zip")
        assert check_printable_on_cc2(stl).reason == REASON_UNSUPPORTED_TYPE
        assert check_printable_on_cc2(broken).reason == REASON_UNSUPPORTED_TYPE

    def test_upload_check_on_raw_bytes(self):
        assert gcode_sliced_for_cc2(("G28\n" + ORCA_CC2_TAIL).encode())
        assert not gcode_sliced_for_cc2(b"; printer_model = Bambu Lab A1\nG28\n")
        assert not gcode_sliced_for_cc2(b"G28\n")

    @pytest.mark.parametrize(
        ("original", "expected"),
        [
            ("benchy.gcode", "benchy.gcode"),
            ("folder/Svuotatasche KTM.gcode", "Svuotatasche KTM.gcode"),
            ("C:\\slices\\x.gcode", "x.gcode"),
            ("a:b*c?.gcode", "a_b_c_.gcode"),
            (".hidden.gcode", "hidden.gcode"),
        ],
    )
    def test_printer_filename(self, original, expected):
        assert printer_filename(original) == expected

    def test_printer_filename_keeps_the_extension_when_cut(self):
        name = printer_filename("x" * 300 + ".gcode")
        assert name.endswith(".gcode") and len(name) == 200

    def test_printer_filename_refuses_a_non_machine_file(self):
        with pytest.raises(ValueError):
            printer_filename("model.stl")


# --- job events -> queue + archive ----------------------------------------------


@pytest.fixture
def sessions(test_engine):
    maker = async_sessionmaker(test_engine, class_=AsyncSession, expire_on_commit=False)
    manager = MagicMock()
    with (
        patch("backend.app.services.provider_jobs.async_session", maker),
        patch("backend.app.services.provider_jobs.printer_manager", manager),
    ):
        provider_jobs._dispatched.clear()
        yield maker, manager
    provider_jobs._dispatched.clear()


async def _printing_job(db_session, printer_factory, archive_factory, filename="benchy.gcode"):
    printer = await printer_factory(name="Centauri 2", model="Centauri 2", provider="elegoo")
    archive = await archive_factory(printer.id, filename=filename, status="archived")
    item = PrintQueueItem(
        printer_id=printer.id,
        archive_id=archive.id,
        status="printing",
        started_at=datetime.now(timezone.utc),
    )
    db_session.add(item)
    await db_session.commit()
    return printer, archive, item


async def _reload(maker, model, row_id):
    async with maker() as db:
        return await db.get(model, row_id)


@pytest.mark.asyncio
class TestJobEvents:
    async def test_finish_closes_queue_and_archive(self, sessions, db_session, printer_factory, archive_factory):
        maker, manager = sessions
        printer, archive, item = await _printing_job(db_session, printer_factory, archive_factory)
        provider_jobs.record_dispatch(printer.id, item.id, "benchy.gcode")

        await provider_jobs.on_provider_job_event(printer.id, JobEvent("started", "benchy.gcode"))
        assert (await _reload(maker, type(archive), archive.id)).status == "printing"

        await provider_jobs.on_provider_job_event(
            printer.id, JobEvent("ended", "benchy.gcode", JobState.FINISHED, inferred=True, progress=99)
        )
        assert (await _reload(maker, PrintQueueItem, item.id)).status == "completed"
        assert (await _reload(maker, type(archive), archive.id)).status == "completed"
        manager.set_awaiting_plate_clear.assert_called_with(printer.id, True)

    async def test_unobserved_end_is_explicit(self, sessions, db_session, printer_factory, archive_factory):
        maker, _ = sessions
        printer, archive, item = await _printing_job(db_session, printer_factory, archive_factory)
        await provider_jobs.on_provider_job_event(printer.id, JobEvent("ended", "benchy.gcode", JobState.UNKNOWN))
        row = await _reload(maker, PrintQueueItem, item.id)
        assert row.status == "failed"
        assert row.error_message == provider_jobs.OUTCOME_NOT_OBSERVED
        assert (await _reload(maker, type(archive), archive.id)).failure_reason == "noStatusUpdate"

    async def test_print_from_the_slicer_is_left_alone(self, sessions, db_session, printer_factory, archive_factory):
        maker, manager = sessions
        printer, archive, item = await _printing_job(db_session, printer_factory, archive_factory)
        provider_jobs.record_dispatch(printer.id, item.id, "benchy.gcode")
        await provider_jobs.on_provider_job_event(printer.id, JobEvent("ended", "from-orca.gcode", JobState.CANCELLED))
        assert (await _reload(maker, PrintQueueItem, item.id)).status == "printing"
        # The plate may hold the other print anyway.
        manager.set_awaiting_plate_clear.assert_called_with(printer.id, True)

    async def test_after_a_restart_the_archive_name_identifies_the_job(
        self, sessions, db_session, printer_factory, archive_factory
    ):
        maker, _ = sessions
        printer, _, item = await _printing_job(db_session, printer_factory, archive_factory, filename="a:b.gcode")
        await provider_jobs.on_provider_job_event(printer.id, JobEvent("ended", "a_b.gcode", JobState.CANCELLED))
        assert (await _reload(maker, PrintQueueItem, item.id)).status == "cancelled"

    async def test_stopped_from_the_queue_closes_the_archive(
        self, sessions, db_session, printer_factory, archive_factory
    ):
        maker, _ = sessions
        printer, archive, item = await _printing_job(db_session, printer_factory, archive_factory)
        provider_jobs.record_dispatch(printer.id, item.id, "benchy.gcode")
        item.status = "cancelled"
        await db_session.commit()
        await provider_jobs.on_provider_job_event(printer.id, JobEvent("ended", "benchy.gcode", JobState.CANCELLED))
        row = await _reload(maker, type(archive), archive.id)
        assert row.status == "cancelled"
        assert row.failure_reason == "userCancelled"

    async def test_print_outside_the_queue_logs_its_outcome(self, sessions, printer_factory, caplog):
        printer = await printer_factory(name="Centauri 2", model="Centauri 2", provider="elegoo")
        with caplog.at_level(logging.INFO, logger="backend.app.services.provider_jobs"):
            await provider_jobs.on_provider_job_event(
                printer.id, JobEvent("ended", "kawasaki.gcode", JobState.FINISHED, inferred=True, progress=99)
            )
            await provider_jobs.on_provider_job_event(printer.id, JobEvent("ended", "orca.gcode", JobState.CANCELLED))
        assert "'kawasaki.gcode' (finished, inferred after 99%) outside the farm queue" in caplog.text
        assert "'orca.gcode' (cancelled) outside the farm queue" in caplog.text
